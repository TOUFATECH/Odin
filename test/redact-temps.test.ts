//  2. Un texte hostile ne bloque pas Odin : 20 000 caractères de blancs (espaces, tabulations, retours à la ligne,
//     espaces insécables, mélange…), seuls ou posés là où une expression hésitait, sont masqués en moins de 200 ms.
//     Avant la correction, 2 000 espaces prenaient plus de dix secondes, et le temps grandissait comme le cube.
//     De même les annonces répétées sans blanc (« mdp » puis quarante « : », « 密码 » puis quarante « 是 », « sk- »,
//     « http:// » sur une ligne) : cinq secondes pour 20 000 caractères avant la correction, le carré de la longueur.
//     Elles sont aussi mesurées à 100 000 caractères : cinq fois plus long, cinq fois la limite, pas vingt-cinq.
// La mesure du temps tourne dans un processus à part, arrêté au bout d'une minute : une expression qui ne finit pas
// fait échouer l'essai, elle ne le bloque pas. Valeurs d'exemple seulement.
