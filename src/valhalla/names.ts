/** Les applicatifs similaires d'une appli, avec leur site quand il est sûr ([] = aucun). Une appli qui n'a pas encore sa
 *  ligne dans SIMILAIRES peut porter un champ `similaires: string[]`. Pur. */
export function similairesDe(m: { id: string; similaires?: unknown }): Array<{ nom: string; site?: string }> {
  const l = SIMILAIRES[m.id] ?? (Array.isArray(m.similaires) ? m.similaires.map(String) : []);
  return l.map((nom) => (SITES_SIMILAIRES[nom] ? { nom, site: SITES_SIMILAIRES[nom] } : { nom }));
}
